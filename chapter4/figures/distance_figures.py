"""Draw the figures of the distance between moving polygons of Sect. 4.6 of chapter 4: the outer Voronoi
diagram of a convex polygon, and a non-convex polygon with its decomposition into convex parts.

The outer Voronoi diagram of a convex polygon divides the plane outside it into the regions closest to
each edge and to each vertex: the region of the edge e_i, from v_i to v_{i+1}, lies between the lines
perpendicular to e_i at its two ends, drawn as red dotted rays at v_i and blue dotted rays at v_{i+1},
and the region of a vertex lies between the rays of its two edges. The non-convex polygon is a cross,
decomposed into three disjoint convex parts, its vertical bar and its two arms, and into two
overlapping convex parts, its vertical and its horizontal bar; each decomposition is checked to be
made of convex parts whose union is the cross, the first one of parts that do not overlap. The pictures are written as TikZ into $OUT (default: out/ below the
working directory), as #planar_graph.py writes the panels of the planar graph figure, which the
chapter inputs: outer_voronoi_diagram_polygon.tex, convex_object.tex, convex_decomposition_1.tex and
convex_decomposition_2.tex.

Usage: python3 distance_figures.py
"""
import math
import os
from shapely.geometry import Polygon
from shapely.ops import unary_union

OUT = os.environ.get('OUT', os.path.join(os.getcwd(), 'out'))
os.makedirs(OUT, exist_ok=True)


def write(name, body):
    with open(os.path.join(OUT, name + '.tex'), 'w') as fh:
        fh.write('% Generated by distance_figures.py\n' + '\n'.join(body) + '\n')


def cycle(pts):
    return ' -- '.join('(%.4f,%.4f)' % p for p in pts) + ' -- cycle'


# Fig. 4.28: a convex pentagon, its vertices counterclockwise
PENTAGON = [(2.2, -5.0), (5.7, -5.6), (7.3, -3.4), (4.7, -1.1), (1.6, -2.3)]
RAY = 1.4  # length of the rays, in the units of the polygon
n = len(PENTAGON)
body = ['\\begin{tikzpicture}[x=0.6cm, y=0.6cm, font=\\scriptsize]',
        '\\filldraw[fill=gray!15, draw=black, semithick] %s;' % cycle(PENTAGON)]
cx = sum(x for x, _ in PENTAGON) / n
cy = sum(y for _, y in PENTAGON) / n
for i in range(n):
    (ax, ay), (bx, by) = PENTAGON[i], PENTAGON[(i + 1) % n]
    lx, ly = bx - ax, by - ay
    d = math.hypot(lx, ly)
    ox, oy = ly / d, -lx / d  # the outward normal of a counterclockwise edge
    body.append('\\draw[red, densely dotted] (%.4f,%.4f) -- ++(%.4f,%.4f);' % (ax, ay, RAY * ox, RAY * oy))
    body.append('\\draw[blue, densely dotted] (%.4f,%.4f) -- ++(%.4f,%.4f);' % (bx, by, RAY * ox, RAY * oy))
    mx, my = (ax + bx) / 2, (ay + by) / 2
    body.append('\\node at (%.4f,%.4f) {$e_%d(t)$};' % (mx + 0.45 * ox, my + 0.45 * oy, i + 1))
    # the name of the vertex inside the polygon, towards its centre
    vx, vy = cx - ax, cy - ay
    k = 0.55 / math.hypot(vx, vy)
    body.append('\\node at (%.4f,%.4f) {$v_%d(t)$};' % (ax + k * vx, ay + k * vy, i + 1))
body.append('\\end{tikzpicture}')
write('outer_voronoi_diagram_polygon', body)

# Fig. 4.29: a cross of three units, its decomposition into three disjoint parts, the vertical bar and
# the two arms, and into two overlapping parts, the vertical and the horizontal bar
CROSS = [(1, 0), (2, 0), (2, 1), (3, 1), (3, 2), (2, 2), (2, 3), (1, 3), (1, 2), (0, 2), (0, 1), (1, 1)]
PARTS = [[(1, 0), (2, 0), (2, 3), (1, 3)], [(0, 1), (1, 1), (1, 2), (0, 2)], [(2, 1), (3, 1), (3, 2), (2, 2)]]
BARS = [[(1, 0), (2, 0), (2, 3), (1, 3)], [(0, 1), (3, 1), (3, 2), (0, 2)]]
cross = Polygon(CROSS)
assert not cross.equals(cross.convex_hull), 'the cross is convex'
for parts in (PARTS, BARS):
    assert all(Polygon(p).equals(Polygon(p).convex_hull) for p in parts), 'a part is not convex'
    assert unary_union([Polygon(p) for p in parts]).equals(cross), 'the parts do not make the cross'
assert sum(Polygon(p).area for p in PARTS) == cross.area, 'the three parts overlap'
assert sum(Polygon(p).area for p in BARS) > cross.area, 'the two bars do not overlap'
STYLE = '\\begin{tikzpicture}[x=0.75cm, y=0.75cm]'
write('convex_object', [STYLE, '\\filldraw[fill=gray!15, draw=black] %s;' % cycle(CROSS),
                        '\\end{tikzpicture}'])
write('convex_decomposition_1', [STYLE] + ['\\filldraw[fill=gray!15, draw=black] %s;' % cycle(p)
                                           for p in PARTS] + ['\\end{tikzpicture}'])
# The two bars are filled half transparent, so that the square where they overlap is darker
write('convex_decomposition_2', [STYLE] + ['\\filldraw[fill=gray!40, fill opacity=0.5, draw=black] %s;'
                                           % cycle(p) for p in BARS] + ['\\end{tikzpicture}'])
